const uint8_t *oled_font_cn_lookup(const char *utf8)
{
  uint8_t i;
  for (i = 0; i < OLED_FONT_CN_COUNT; i++)
  {
    if (s_cn_map[i].utf8[0] == (uint8_t)utf8[0] &&
        s_cn_map[i].utf8[1] == (uint8_t)utf8[1] &&
        s_cn_map[i].utf8[2] == (uint8_t)utf8[2])
    {
      return oled_font_cn[i];
    }
  }
  return 0;
}

